func TestParseShowFolder(t *testing.T) {
	cases := []struct {
		name string
		want Show
		ok   bool
	}{
		{"Glass Harbor - 2024-06-14 - The Lantern Room, Portland, OR [SBD]",
			Show{Date: "2024-06-14", Venue: "The Lantern Room", Location: "Portland, OR", Source: "SBD"}, true},
		{"gh2024-06-14.sbd.miller.flac16", Show{Date: "2024-06-14", Source: "SBD"}, true},
		// The etree shorthand: a two-digit year after the band's letters.
		{"gd77-05-08.aud.hicks.4982.shnf", Show{Date: "1977-05-08", Source: "AUD"}, true},
		{"cs19-03-02.mtx.flac24", Show{Date: "2019-03-02", Source: "MTX"}, true},
		{"2023.05.12 Red Rocks Amphitheatre (Matrix)", Show{Date: "2023-05-12", Venue: "Red Rocks Amphitheatre", Source: "MTX"}, true},
		{"1999-12-31 Big Cypress, FL", Show{Date: "1999-12-31", Venue: "Big Cypress", Location: "FL"}, true},
		// No full date: a studio album, not a show.
		{"Glass Harbor - 2019 - Signal Fires", Show{}, false},
		{"Signal Fires", Show{}, false},
		// Not a real date.
		{"gh2024-13-40.sbd", Show{}, false},
	}
	for _, c := range cases {
		got, ok := ParseShowFolder(c.name)
		if ok != c.ok || got != c.want {
			t.Errorf("ParseShowFolder(%q) = %+v, %v; want %+v, %v", c.name, got, ok, c.want, c.ok)
		}
	}
}

func TestParseInfoFile(t *testing.T) {
	text := "\uFEFFGlass Harbor\r\n2024-06-14\r\nThe Lantern Room\r\nPortland, OR\r\n\r\n" +
		"Source: SBD > Zoom F8 > SD\r\nLineage: SD > WAV > Audacity > FLAC (level 8)\r\nTaper: Mo Ellery\r\n\r\n" +
		"Set 1:\r\nd1t01 - Low Tide\r\nd1t02 - Breakwater ->\r\n"
	got := ParseInfoFile(text)
	want := Show{Date: "2024-06-14", Venue: "The Lantern Room", Location: "Portland, OR", Source: "SBD",
		SourceDetail: "SBD > Zoom F8 > SD", Lineage: "SD > WAV > Audacity > FLAC (level 8)", Taper: "Mo Ellery", Artist: "Glass Harbor"}
	if got != want {
		t.Errorf("got  %+v\nwant %+v", got, want)
	}
	// A spelled-out date, a venue with its place on one line, a matrix.
	got = ParseInfoFile("Cedar Static\nSaturday, March 2, 2019\nThe Crooked Mile, Ithaca, NY\n\nsource: Matrix of SBD and AUD (Schoeps)\n")
	if got.Date != "2019-03-02" || got.Venue != "The Crooked Mile" || got.Location != "Ithaca, NY" || got.Source != "MTX" || got.Artist != "Cedar Static" {
		t.Errorf("spelled-out date: %+v", got)
	}
	// Notes without the header shape are never read as a venue.
	got = ParseInfoFile("Thanks to everyone who helped!\nSet one was great.\nEncore below.\n")
	if got.Venue != "" || got.Artist != "" || got.Date != "" {
		t.Errorf("free text read as a header: %+v", got)
	}
}

func TestParseChecksumFile(t *testing.T) {
	md5 := "; generated by a checksum tool\n" +
		"0123456789abcdef0123456789ABCDEF *gh2024-06-14d1t01.flac\n" +
		"fedcba9876543210fedcba9876543210  CD2\\gh2024-06-14d2t01.flac\n" +
		"not a checksum line\n" +
		"0123456789abcdef0123456789abcdef  ../escape.flac\n"
	got := ParseChecksumFile("show.md5", md5)
	want := []Checksum{
		{File: "gh2024-06-14d1t01.flac", Algorithm: "md5", Value: "0123456789abcdef0123456789abcdef"},
		{File: "CD2/gh2024-06-14d2t01.flac", Algorithm: "md5", Value: "fedcba9876543210fedcba9876543210"},
	}
	if !reflect.DeepEqual(got, want) {
		t.Errorf("md5:\n got %+v\nwant %+v", got, want)
	}
	ffp := "gh2024-06-14d1t01.flac:aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa\r\nweird:name.flac:bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb\r\n"
	got = ParseChecksumFile("gh2024-06-14.ffp", ffp)
	want = []Checksum{
		{File: "gh2024-06-14d1t01.flac", Algorithm: "ffp", Value: "aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa"},
		{File: "weird:name.flac", Algorithm: "ffp", Value: "bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb"},
	}
	if !reflect.DeepEqual(got, want) {
		t.Errorf("ffp:\n got %+v\nwant %+v", got, want)
	}
	if got := ParseChecksumFile("notes.txt", md5); got != nil {
		t.Errorf("a .txt file parsed as checksums: %v", got)
	}
}

func TestTrackNumbers(t *testing.T) {
	cases := []struct {
		file        string
		disc, track int
		title       string
	}{
		{"gh2024-06-14d1t01.flac", 1, 1, "gh2024-06-14d1t01"},
		{"ph97-11-22d2t07.shn", 2, 7, "ph97-11-22d2t07"},
		{"gd77-05-08s3t12.flac", 3, 12, "gd77-05-08s3t12"},
		{"gd77-05-08t04.flac", 0, 4, "gd77-05-08t04"},
		{"03 - Low Tide.mp3", 0, 3, "Low Tide"},
		{"1-03 Breakwater.flac", 1, 3, "Breakwater"},
		{"07. Harbor Lights.m4a", 0, 7, "Harbor Lights"},
		{"Exit 03.flac", 0, 0, "Exit 03"},
	}
	for _, c := range cases {
		d, tr, title := TrackNumbers(c.file)
		if d != c.disc || tr != c.track || title != c.title {
			t.Errorf("TrackNumbers(%q) = %d, %d, %q; want %d, %d, %q", c.file, d, tr, title, c.disc, c.track, c.title)
		}
	}
}

func TestMusicHelpers(t *testing.T) {
	if foldKey("Umphrey's  McGee") != foldKey("umphreys mcgee") || foldKey("R.E.M.") != "rem" {
		t.Error("foldKey does not fold punctuation and case")
	}
	if sortName("The Band") != "Band, The" || sortName("Theory") != "Theory" {
		t.Errorf("sortName: %q %q", sortName("The Band"), sortName("Theory"))
	}
	for in, want := range map[string]float64{"-6.20 dB": -6.2, "+1.5 dB": 1.5, "0.988": 0.988} {
		if got, ok := gainOf(in); !ok || got != want {
			t.Errorf("gainOf(%q) = %v %v", in, got, ok)
		}
	}
	if _, ok := gainOf("loud"); ok {
		t.Error("gainOf accepted text")
	}
	for in, want := range map[string]string{"1997": "1997", "1997-11-22": "1997-11-22", "1997-11": "1997-11", "1997/11/22": "1997-11-22", "x": ""} {
		if got := dateOf(in); got != want {
			t.Errorf("dateOf(%q) = %q, want %q", in, got, want)
		}
	}
	if numberOf("3/12") != 3 || numberOf("07") != 7 || numberOf("x") != 0 {
		t.Error("numberOf")
	}
	if d := DiscFolder("CD2"); d != 2 {
		t.Errorf("DiscFolder(CD2) = %d", d)
	}
	if d := DiscFolder("Disc 1"); d != 1 {
		t.Errorf("DiscFolder(Disc 1) = %d", d)
	}
	if d := DiscFolder("Signal Fires"); d != 0 {
		t.Errorf("DiscFolder(Signal Fires) = %d", d)
	}
}

// Grouping as a pure function: compilations with and without the flag, an
// album artist tag that wins over track artists, the two discs of a set in two
// folders, and a show whose guest on one track does not make it a compilation.
func TestGroupMusic(t *testing.T) {
	file := func(rel string, tags map[string]string) *musicFile {
		return &musicFile{rel: rel, abs: "/m/" + rel, tags: tags, probeStatus: "ok"}
	}
	files := []*musicFile{
		file("Sampler/01.mp3", map[string]string{"artist": "Lumen Drive", "album": "Night Market Sampler", "track": "1"}),
		file("Sampler/02.mp3", map[string]string{"artist": "Cedar Static", "album": "Night Market Sampler", "track": "2"}),
		file("Flagged/01.m4a", map[string]string{"artist": "Cedar Static", "album": "Low Orbit Covers", "compilation": "1"}),
		file("Glass Harbor/Tide Tables/01.flac", map[string]string{"artist": "Glass Harbor feat. Mo", "album_artist": "Glass Harbor", "album": "Tide Tables", "track": "1"}),
		file("Glass Harbor/Tide Tables/02.flac", map[string]string{"artist": "Glass Harbor", "ALBUMARTIST": "Glass Harbor", "album": "Tide Tables", "track": "2"}),
		file("Glass Harbor/Box Set/CD1/01 One.flac", map[string]string{"artist": "Glass Harbor", "album": "Box Set"}),
		file("Glass Harbor/Box Set/CD2/01 Two.flac", map[string]string{"artist": "Glass Harbor", "album": "Box Set"}),
		file("Glass Harbor/gh2024-06-14.sbd/gh2024-06-14d1t01.flac", map[string]string{"artist": "Glass Harbor", "title": "Low Tide"}),
		file("Glass Harbor/gh2024-06-14.sbd/gh2024-06-14d1t02.flac", map[string]string{"artist": "Glass Harbor with Mo Ellery", "title": "Breakwater"}),
		file("Glass Harbor/gh2024-06-14.sbd/gh2024-06-14d1t03.flac", map[string]string{"artist": "Glass Harbor", "title": "Undertow"}),
	}
	folders := map[string]*musicFolder{
		"Glass Harbor/gh2024-06-14.sbd": {rel: "Glass Harbor/gh2024-06-14.sbd", infoPath: "x.txt",
			infoText: "Glass Harbor\n2024-06-14\nThe Lantern Room\nPortland, OR\n"},
	}
	albums, artists := groupMusic(files, folders)
	by := map[string]*albumPlan{}
	for _, a := range albums {
		by[a.title] = a
	}
	if len(albums) != 5 {
		t.Fatalf("%d albums, want 5: %v", len(albums), by)
	}
	if a := by["Night Market Sampler"]; a.artist.name != VariousArtists || !a.compilation || a.tracks[0].artist.name != "Lumen Drive" {
		t.Errorf("unflagged compilation: artist %q, compilation %v", a.artist.name, a.compilation)
	}
	if a := by["Low Orbit Covers"]; a.artist.name != VariousArtists || !a.compilation {
		t.Errorf("flagged compilation: artist %q", a.artist.name)
	}
	if a := by["Tide Tables"]; a.artist.name != "Glass Harbor" || a.compilation || len(a.tracks) != 2 || a.tracks[0].artistName != "Glass Harbor feat. Mo" {
		t.Errorf("album artist tag: %+v", a)
	}
	if a := by["Box Set"]; len(a.tracks) != 2 || a.tracks[0].disc != 1 || a.tracks[1].disc != 2 || a.tracks[1].title != "Two" {
		t.Errorf("box set: %d tracks", len(a.tracks))
	}
	show := by["2024-06-14 The Lantern Room, Portland, OR"]
	if show == nil || !show.live || show.compilation || show.artist.name != "Glass Harbor" || show.show.Source != "SBD" || len(show.tracks) != 3 {
		t.Fatalf("live show: %+v", show)
	}
	if show.tracks[1].artist.name != "Glass Harbor with Mo Ellery" || show.tracks[2].track != 3 {
		t.Errorf("show tracks: %q %d", show.tracks[1].artist.name, show.tracks[2].track)
	}
	if _, ok := artists[foldKey("Lumen Drive")]; !ok {
		t.Error("a compilation's track artist has no artist row")
	}
}
